// Language detection
const detectLanguage = async () => {
  try {
    const savedLanguage = await SecureStore.getItemAsync('user_language');
    if (savedLanguage && SUPPORTED_LANGUAGES.includes(savedLanguage)) {
      return savedLanguage;
    }
  } catch {
    // Ignore and fallback to system locale detection
  }

  try {
    const locales = Localization.getLocales();
    const systemLang = locales && locales[0] ? locales[0].languageCode : 'en';
    if (systemLang && SUPPORTED_LANGUAGES.includes(systemLang)) {
      return systemLang;
    }
  } catch {
    // Ignore and default to 'en'
  }

  return 'en';
};

// Initialize i18n setup
const initI18n = async () => {
  const language = await detectLanguage();
  
  await i18n
    .use(initReactI18next)
    .init({
      resources,
      lng: language,
      fallbackLng: 'en',
      compatibilityJSON: 'v3',
      interpolation: {
        escapeValue: false,
      },
    } as any);
};

initI18n();

export default i18n;
